"""Aggregate API router mounted under /api/v1."""

from fastapi import APIRouter

from app.routers import (
    auth,
    health,
    scheduling,
    users,
    allergy,
    appointment,
    appointment_type,
    availability_slot,
    care_plan,
    care_plan_goal,
    care_plan_task,
    claim,
    claim_line,
    clinician,
    document,
    insurance_policy,
    lab_order,
    lab_result,
    location,
    medication,
    message,
    message_attachment,
    message_thread,
    notification,
    organization,
    patient,
    pharmacy,
    prescription,
    reminder,
    telehealth_participant,
    telehealth_session,
)

